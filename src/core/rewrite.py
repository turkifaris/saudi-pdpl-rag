def rewrite(q: str, timeout: int = 60) -> tuple[str, bool]:
    """يرجع (السؤال المستخدَم، هل تغيّر)."""
    try:
        r = requests.post(OLLAMA, timeout=timeout, json={
            "model": MODEL,
            "stream": False,
            "options": {"temperature": 0.0},
            "messages": [
                {"role": "system", "content": SYSTEM},
                *[m for u, a in SHOTS for m in
                  ({"role": "user", "content": u}, {"role": "assistant", "content": a})],
                {"role": "user", "content": q},
            ],
        })
        r.raise_for_status()
        out = r.json()["message"]["content"].strip()
    except Exception:
        return q, False

    out = out.split("\n")[0].strip().strip('"«»')
    out = re.sub(r"^\s*(السؤال|الصياغة|إعادة الصياغة)\s*[:：]\s*", "", out)

    # حواجز أمان: نرفض المخرج المشبوه ونرجع الأصل
    if not out or len(out) > len(q) * 3 + 60 or len(out) < 8:
        return q, False
    if re.search(r"[A-Za-z]", out):
        return q, False
    return out, out != q

